test_that("tied ROC optima choose smallest finite native threshold", {
  skip_if_not_installed("pROC"); v <- fixture_view()
  a <- matrix(c(1,2,3,4),4,1,dimnames=list(paste0("s",1:4),"F1"))
  v <- .make_representation(a,v$effects[,1,drop=FALSE],utils::modifyList(v$manifest,list(native_indices=1)))
  md <- data.frame(sample=rownames(a),group=c("yes","no","yes","no"))
  r <- factor_specificity(v,md,"group",groups="yes",threshold_method="youden")
  native <- pROC::roc(md$group=="yes",a[,1],levels=c(FALSE,TRUE),direction="<",quiet=TRUE)
  best <- pROC::coords(native,"best",best.method="youden",transpose=FALSE)
  expect_gt(nrow(best),1)
  expect_equal(r$threshold_ties,nrow(best))
  expect_equal(r$threshold,min(best$threshold[is.finite(best$threshold)]))
})
