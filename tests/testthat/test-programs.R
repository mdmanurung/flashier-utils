  expect_silent(ggplot2::ggplot_build(plot_factor_gates(gate,E,display="density")))
  x <- compare_factor_groups(v,md,"group",c("b","a")); y <- compare_factor_groups(v,md,"group",c("a","b"))
  expect_equal(plot_factor_contrasts(x,y)$data$x,-plot_factor_contrasts(x,y)$data$y)
  expect_identical(.Random.seed,old)
})
