test_that("native pROC direction, constants and absent groups are explicit", {
  skip_if_not_installed("pROC"); v <- fixture_view()
  md <- data.frame(sample=c("s3","s1","s2"),group=c("high","low","low"),unit=c("u2","u1","u1"))
  r <- factor_specificity(v,md,"group",groups=c("high","absent"),unit_col="unit")
  expect_equal(r$auc[r$factor=="F1" & r$group=="high"],1)
  expect_equal(factor_specificity(v,md,"group",groups="high",direction="negative")$auc[1],0)
  expect_true(all(r$status[r$group=="absent"]=="unavailable_absent_class"))
  roc <- pROC::roc(c(FALSE,FALSE,TRUE),v$activity[,1],levels=c(FALSE,TRUE),direction="<",quiet=TRUE)
  best <- pROC::coords(roc,"best",best.method="closest.topleft",transpose=FALSE)
  expect_equal(r$threshold[1],min(best$threshold[is.finite(best$threshold)]))
  v2 <- .make_representation(cbind(F1=c(s1=1,s2=1,s3=1)),v$effects[,"F1",drop=FALSE],utils::modifyList(v$manifest,list(native_indices=1)))
  c <- factor_specificity(v2,md,"group",groups="high")
  expect_equal(c$auc,0.5); expect_true(is.na(c$threshold)); expect_equal(c$status,"constant_predictor")
})
test_that("marker gates use identical populations and deterministic activity ties", {
  v <- fixture_view(); M <- cbind(CD1=c(s3=2,s2=0,s1=3),CD2=c(0,1,0))
  r <- factor_gate_alignment(v,M,"F1",positive="CD1",negative="CD2",thresholds=c(CD1=1,CD2=0.5))
  expect_equal(r$gate_ids,c("s1","s3")); expect_equal(r$activity_ids,c("s3","s2"))
  expect_equal(r$summary$overlap_fraction,0.5); expect_equal(r$summary$n_gate,r$summary$n_activity)
  empty <- factor_gate_alignment(v,M,"F1",positive="CD1",thresholds=c(CD1=5))
  expect_true(is.na(empty$summary$jaccard)); expect_length(empty$activity_ids,0)
  expect_error(factor_gate_alignment(v,M,"F1",positive="missing",thresholds=c(CD1=1)),"Unknown")
  expect_error(factor_gate_alignment(v,M,"F1",positive="CD1",thresholds=c(CD2=1)),"Missing")
  low <- factor_gate_alignment(v,M,"F1",positive="CD1",negative="CD2",thresholds=c(CD1=1,CD2=0.5),direction="low")
  expect_equal(low$gate_ids,r$gate_ids); expect_equal(low$activity_ids,c("s1","s2"))
  expect_equal(low$summary$direction,"low"); expect_equal(attr(low,"analysis_metadata")$tie_rule,"ascending_activity_then_sample_ID")
  expect_equal(r$summary$direction,"high")
  expect_error(factor_gate_alignment(v,M,"F1",positive="CD1",thresholds=c(CD1=1),direction="up"),"arg")
  c <- correlate_factor_markers(v,M)
  expect_equal(c$correlation[1],cor(v$activity[,1],M[rownames(v$activity),1]))
})
test_that("mclust candidates match namespace-only native fits and preserve RNG", {
  skip_if_not_installed("mclust")
  set.seed(13); M <- cbind(CD1=c(rnorm(100,2,0.1),rnorm(100,5,0.1))); rownames(M) <- paste0("s",1:200)
  old <- .Random.seed
  r <- estimate_marker_thresholds(M,thresholds=c(CD1=3))
  expect_identical(.Random.seed,old)
  expect_equal(r$thresholds$threshold,3); expect_equal(r$thresholds$source,"supplied")
  mclustBIC <- mclust::mclustBIC
  native <- .with_seed(42,mclust::Mclust(M[,1],G=2,verbose=FALSE))
  expect_equal(r$thresholds$candidate,max(M[native$classification==which.min(native$parameters$mean),1]))
  expect_equal(r$thresholds$bic_two,native$bic)
  expect_false(r$thresholds$manual_review)
  expect_true(estimate_marker_thresholds(M[1:10,,drop=FALSE])$thresholds$manual_review)
  constant <- M; constant[,1] <- 2
  expect_equal(estimate_marker_thresholds(constant)$thresholds$status,"constant_marker")
})
